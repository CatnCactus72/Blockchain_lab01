"""Rebuild report tables and chart from the saved run; does not run the simulator."""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
records = json.loads((HERE / "evidence/scenario_metrics.json").read_text(encoding="utf-8"))
selected = [r for r in records if r["seed"] is None]
assert len(selected) == 9
test_lines = (HERE / "evidence/test_results.txt").read_text(encoding="utf-8").splitlines()
assert sum(s.startswith("PASS ") for s in test_lines) == 127
assert not any(s.startswith(("FAIL ", "ERROR ")) for s in test_lines)

rows = []
for label, r in zip(["T1", "T2", "T3", "T4", "T5", "T6", "T7", "X1", "X2"], selected):
    heights = set(r["honest_heights"].values())
    assert len(heights) == 1
    assert r["summary"]["safety_prefixes"]
    rows.append(f"{label} & {r['summary']['duration_ms']/1000:.3f} & {len(r['honest_heights'])} & {heights.pop()} & {r['applied_at_first_honest']} & {r['events'].get('DROP', 0)} & {sum(r['reject_reasons'].values())} " + r"\\")

hash_rows = []
for name, label in [("t1_normal", "T1"), ("t7_byzantine_equivocate", "T7")]:
    a, b, c = [r for r in records if r["scenario"] == name and r["seed"] is not None]
    assert (a["seed"], b["seed"], c["seed"]) == (42, 42, 43)
    assert a["log_sha256"] == b["log_sha256"] != c["log_sha256"]
    assert a["summary"]["nodes"] == b["summary"]["nodes"]
    hash_rows.append(f"{label} & \\code{{{a['log_sha256'][:12]}}} & \\code{{{b['log_sha256'][:12]}}} & \\code{{{c['log_sha256'][:12]}}} " + r"\\")

plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
fig, ax = plt.subplots(figsize=(6.6, 2.3), layout="constrained")
for idx, label, color in [(0, "T1", "#17364D"), (4, "T5", "#C56D31"), (5, "T6", "#007F83"), (6, "T7", "#7956A1")]:
    timeline = selected[idx]["finalization_timeline"]
    ax.step([0] + [p["ms"]/1000 for p in timeline], [0] + [int(p["height"]) for p in timeline], where="post", label=label, color=color, linewidth=1.6)
ax.axvline(30, linestyle="--", color="#89949C", linewidth=1)
ax.text(30.5, 0.7, "GST của T5", fontsize=8, color="#52636F")
ax.set(xlabel="Thời gian ảo (giây)", ylabel="Height đã finalize tại N0", xlim=(0, 53), ylim=(0, 10.5), yticks=[0, 2, 4, 6, 8, 10])
ax.grid(axis="y", alpha=0.18)
ax.legend(loc="upper left", ncol=4, frameon=False)
(HERE / "figures").mkdir(exist_ok=True)
fig.savefig(HERE / "figures/finalization.pdf")
fig.savefig(HERE / "figures/finalization.png", dpi=300)
plt.close(fig)

text = r"""% Generated by report/build_results.py from saved evidence.
Lần chạy ngày 11/11/2026: \textbf{127/127 tests PASS}, không có FAIL/ERROR; 15 lượt mô phỏng gồm 9 scenario và 6 lượt phục vụ T8. Bảng dưới dùng seed 42, thời gian ảo từ summary, không phải thời gian CPU.

{\small\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrrrr}
\toprule
\textbf{Ca} & \textbf{Giây ảo} & \textbf{Node đúng} & \textbf{Height} & \textbf{TX tại N0} & \textbf{DROP} & \textbf{REJECT}\\\midrule
""" + "\n".join(rows) + r"""
\bottomrule\end{tabular*}}
\figcap{Bảng 1. Height cuối bằng nhau trên các node đúng; TX là số sự kiện TX\_APPLIED riêng tại N0. DROP/REJECT được đếm trên toàn log. T1--T7/X1 đều hội tụ ở height 10; X2 dừng ở 120 s với height 0.}

\begin{center}
\includegraphics[width=0.94\linewidth]{report/figures/finalization.png}
\end{center}
\figcap{Hình 3. Tiến độ tại N0: T5 cần 51.464 s để toàn bộ node đúng đạt đích, so với 15.153 s ở T1. Đường nét đứt chỉ GST của T5; không phải một mốc của ba ca còn lại.}

{\small
\textbf{Quan sát lỗi:} T3 ghi 596 BAD\_SIGNATURE và 27 WRONG\_DOMAIN; T4 có 10 REPLAYED\_TX; T7 có 304 CONFLICTING\_VOTE. T5 có 1133 DROP và 80 DUPLICATE\_VOTE; T6 có 1 DUPLICATE\_VOTE. Các REJECT này phản ánh guard đang hoạt động, không phải test thất bại. T1 vẫn có 4232 DUP do cùng message đi tới node qua nhiều đường gossip, dù Link không tiêm lỗi duplicate. X1 áp dụng 114 TX tại N0; chưa kết luận mọi TX đã sinh đều được đưa vào chain.

\textbf{T8 -- tính xác định.} Hai log seed 42 trùng toàn bộ byte theo test, cùng final state hash; seed 43 cho log khác. Bảng 2 ghi 12 ký tự đầu SHA-256 để nhận diện; đối chiếu thực tế dùng digest đầy đủ và log gốc.

\begin{tabularx}{\linewidth}{lYYY}
\toprule
\textbf{Ca} & \textbf{Seed 42 / lần 1} & \textbf{Seed 42 / lần 2} & \textbf{Seed 43}\\\midrule
""" + "\n".join(hash_rows) + r"""
\bottomrule\end{tabularx}
\par
}
"""
(HERE / "results.tex").write_text(text, encoding="utf-8")
print("Verified 127 PASS, 15 runs and determinism digests; rebuilt results.tex and finalization.pdf.")
